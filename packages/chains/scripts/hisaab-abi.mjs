import { execFileSync } from 'node:child_process'
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const at = (p) => fileURLToPath(new URL(p, import.meta.url))
const abi = execFileSync('forge', ['inspect', 'Hisaab', 'abi', '--json'], {
  cwd: at('../../../contracts/evm'),
  encoding: 'utf8',
})
const out = at('../src/hisaab-abi.ts')
writeFileSync(
  out,
  `// Generated by scripts/hisaab-abi.mjs from contracts/evm. Don't edit.\nexport const hisaabAbi = ${abi.trim()} as const\n`,
)
execFileSync(at('../../../node_modules/.bin/biome'), ['format', '--write', out], {
  stdio: 'inherit',
})
